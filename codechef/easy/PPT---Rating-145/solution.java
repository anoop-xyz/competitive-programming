import java.util.*;
import java.lang.*;
import java.io.*;

class Codechef
{
	public static void main (String[] args) throws java.lang.Exception
	{
		Scanner sc=new Scanner(System.in);
		int n=sc.nextInt();
		
		if (n*30 <= 600) {
		    System.out.println((600-(n*30))/30);
		}
		else {
		    System.out.println();
		    
		}
		

	}
}
